import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const distDir = join(root, "dist");

export function loadTokens() {
  return JSON.parse(readFileSync(join(root, "tokens", "tokens.json"), "utf8"));
}

const px = (value) => `${value}px`;

function shadowCss({ x, y, blur, spread, color }) {
  return `${px(x)} ${px(y)} ${px(blur)} ${px(spread)} ${color}`;
}

function modeVars(tokens, mode, indent) {
  return Object.entries(tokens.color.semantic)
    .map(([name, entry]) => `${indent}--ds-${name}: ${entry[mode]};`)
    .join("\n");
}

function colorVarsCss(tokens) {
  return [
    `:root {\n${modeVars(tokens, "light", "  ")}\n}`,
    `@media (prefers-color-scheme: dark) {\n  :root:not([data-theme="light"]) {\n${modeVars(tokens, "dark", "    ")}\n  }\n}`,
    `:root[data-theme="dark"] {\n${modeVars(tokens, "dark", "  ")}\n}`,
  ].join("\n\n");
}

function themeCss(tokens) {
  const brand = Object.entries(tokens.color.brand).map(
    ([name, value]) => `  --color-brand-${name}: ${value};`,
  );
  const semantic = Object.keys(tokens.color.semantic).map(
    (name) => `  --color-${name}: var(--ds-${name});`,
  );
  const sizes = Object.entries(tokens.font.size).flatMap(([name, { size, lineHeight }]) => [
    `  --text-${name}: ${px(size)};`,
    ...(lineHeight ? [`  --text-${name}--line-height: ${px(lineHeight)};`] : []),
  ]);
  const staticTheme = [
    `  --font-sans: ${tokens.font.family.web};`,
    ...brand,
    ...Object.entries(tokens.radius).map(([name, value]) => `  --radius-${name}: ${px(value)};`),
    ...Object.entries(tokens.space).map(([name, value]) => `  --spacing-${name}: ${px(value)};`),
    ...Object.entries(tokens.shadow).map(([name, value]) => `  --shadow-${name}: ${shadowCss(value)};`),
    ...Object.entries(tokens.font.tracking).map(([name, value]) => `  --tracking-${name}: ${px(value)};`),
    ...sizes,
  ];
  return [
    "/* Generated by scripts/build.mjs from tokens/tokens.json. Do not edit. */",
    colorVarsCss(tokens),
    `@theme {\n${staticTheme.join("\n")}\n}`,
    `@theme inline {\n${semantic.join("\n")}\n}`,
    "",
  ].join("\n\n");
}

function nativeCss(tokens) {
  return [
    "/* Generated by scripts/build.mjs from tokens/tokens.json. Do not edit. */",
    "/* The user app is dark only, so only the dark values are shipped. */",
    `:root {\n${modeVars(tokens, "dark", "  ")}\n}`,
    "",
  ].join("\n\n");
}

function presetCjs(tokens) {
  const colors = {
    brand: tokens.color.brand,
    ...Object.fromEntries(
      Object.keys(tokens.color.semantic).map((name) => [name, `var(--ds-${name})`]),
    ),
  };
  const fontSize = Object.fromEntries(
    Object.entries(tokens.font.size).map(([name, { size, lineHeight }]) => [
      name,
      lineHeight ? [px(size), { lineHeight: px(lineHeight) }] : px(size),
    ]),
  );
  const preset = {
    theme: {
      extend: {
        colors,
        fontFamily: { sans: [tokens.font.family.web] },
        fontSize,
        borderRadius: Object.fromEntries(
          Object.entries(tokens.radius).map(([name, value]) => [name, px(value)]),
        ),
        spacing: Object.fromEntries(
          Object.entries(tokens.space).map(([name, value]) => [name, px(value)]),
        ),
        boxShadow: Object.fromEntries(
          Object.entries(tokens.shadow).map(([name, value]) => [name, shadowCss(value)]),
        ),
        letterSpacing: Object.fromEntries(
          Object.entries(tokens.font.tracking).map(([name, value]) => [name, px(value)]),
        ),
      },
    },
  };
  return `/* Generated by scripts/build.mjs from tokens/tokens.json. Do not edit. */\nmodule.exports = ${JSON.stringify(preset, null, 2)};\n`;
}

function publicTokens(tokens) {
  const semantic = Object.fromEntries(
    Object.entries(tokens.color.semantic).map(([name, { light, dark }]) => [name, { light, dark }]),
  );
  return {
    color: { brand: tokens.color.brand, semantic },
    radius: tokens.radius,
    space: tokens.space,
    shadow: tokens.shadow,
    font: tokens.font,
  };
}

function literalType(value, indent = "") {
  if (typeof value === "string") return JSON.stringify(value);
  if (typeof value === "number") return String(value);
  const inner = `${indent}  `;
  const lines = Object.entries(value).map(
    ([key, child]) => `${inner}readonly ${JSON.stringify(key)}: ${literalType(child, inner)};`,
  );
  return `{\n${lines.join("\n")}\n${indent}}`;
}

function tokensJs(tokens) {
  return `// Generated by scripts/build.mjs from tokens/tokens.json. Do not edit.\nexport const tokens = ${JSON.stringify(publicTokens(tokens), null, 2)};\n`;
}

function tokensDts(tokens) {
  return `// Generated by scripts/build.mjs from tokens/tokens.json. Do not edit.\nexport declare const tokens: ${literalType(publicTokens(tokens))};\n`;
}

export function buildAll(tokens) {
  return {
    "theme.css": themeCss(tokens),
    "native.css": nativeCss(tokens),
    "tailwind-preset.cjs": presetCjs(tokens),
    "tokens.js": tokensJs(tokens),
    "tokens.d.ts": tokensDts(tokens),
  };
}

function writeDist() {
  mkdirSync(distDir, { recursive: true });
  for (const [file, content] of Object.entries(buildAll(loadTokens()))) {
    writeFileSync(join(distDir, file), content);
  }
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeDist();
}
